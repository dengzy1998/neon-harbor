const PLACES = [{ x: -168, z: 216 }, { x: 120, z: 144 }, { x: 0, z: -216 }, { x: 288, z: 24 }, { x: -120, z: -72 }];
export class Missions {
  constructor(hooks = {}) { this.hooks = hooks; this.done = 0; this.mission = null; this.stageIndex = 0; this.result = null; this.jobCounter = 0; this.elapsed = 0; this.jobTime = 150; }
  get current() { if (!this.mission) return null; const stage = this.mission.stages[this.stageIndex]; return { title: this.mission.title, stageText: stage?.text || '', index: this.stageIndex + 1, count: this.mission.stages.length }; }
  startNext() { if (this.mission || this.done >= STORY.length) return false; this._start(STORY[this.done]); return true; }
  _start(mission) { this.mission = mission; this.stageIndex = 0; this.elapsed = 0; this.result = null; for (const line of mission.intro || []) this.hooks.dialogue?.show(...line); this._mark(); }
  _mark() { const stage = this.mission?.stages[this.stageIndex]; if (!stage) return; this.hooks.setMarker?.(stage.x, stage.z, stage.text, stage); }
  startJob() { if (this.mission) return false; const a = this.jobCounter++ % PLACES.length; const b = (a + 1 + (this.jobCounter % (PLACES.length - 1))) % PLACES.length; this._start({ id: 'job', title: 'Harbor Courier', giver: 'otto', intro: [], outro: [], reward: { cash: 240, rp: 35 }, stages: [{ text: 'Pick up the courier parcel', type: 'pickup', ...PLACES[a], radius: 12 }, { text: 'Deliver the courier parcel', type: 'deliver', ...PLACES[b], radius: 12 }] }); this.jobTime = 150; return true; }
  update(dt, ctx = {}) { if (!this.mission) return; this.elapsed += dt; const stage = this.mission.stages[this.stageIndex]; let complete = false; if (stage.type === 'escape') complete = (this.hooks.wantedStars?.() ?? ctx.wantedStars ?? 0) === 0; else if (stage.type === 'fight') complete = (this.hooks.guardsAlive?.() ?? 0) <= 0; else { const pos = ctx.playerPos || this.hooks.playerPos?.(); if (pos && stage.x !== undefined) complete = Math.hypot(pos.x - stage.x, pos.z - stage.z) < (stage.radius || 12); if (complete && stage.heat) complete = (this.hooks.wantedStars?.() ?? ctx.wantedStars ?? 0) >= 2; }
    if (!complete) return; this.hooks.clearMarker?.(); this.stageIndex++; if (this.stageIndex < this.mission.stages.length) { const next = this.mission.stages[this.stageIndex]; if (next.type === 'fight') this.hooks.spawnGuards?.(4); this._mark(); return; } this._finish(); }
  _finish() { const mission = this.mission; const timed = mission.id === 'job'; const remaining = Math.max(0, this.jobTime - this.elapsed); const factor = timed ? 1 + remaining / this.jobTime : 1; const reward = { cash: Math.round(mission.reward.cash * factor), rp: Math.round(mission.reward.rp * factor) }; for (const line of mission.outro || []) this.hooks.dialogue?.show(...line); this.hooks.onReward?.(reward); this.result = { success: true, title: mission.title, ...reward, seconds: this.elapsed }; if (mission.id !== 'job') this.done++; this.hooks.clearMarker?.(); this.mission = null; }
  fail() { if (!this.mission) return; this.hooks.clearMarker?.(); this.hooks.dialogue?.clear?.(); this.result = { success: false, title: this.mission.title }; this.mission = null; this.stageIndex = 0; }
}
