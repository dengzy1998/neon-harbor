import * as THREE from 'three';
import { createCar, driveStep } from '../vehicles/Vehicles.js';
const strand = [-216, -144, -72, 0, 72, 144, 216].map(z => ({ x: 288, z }));
const docklands = [{ x: -288, z: 216 }, { x: -216, z: 216 }, { x: -216, z: 288 }, { x: -72, z: 288 }, { x: -72, z: 216 }, { x: -168, z: 216 }, { x: -288, z: 216 }];
const lantern = [{ x: 72, z: 144 }, { x: 216, z: 144 }, { x: 216, z: 288 }, { x: 72, z: 288 }, { x: 72, z: 144 }];
export const RACES = [{ id: 'strand-sprint', name: 'Strand Sprint', checkpoints: strand }, { id: 'docklands-dash', name: 'Docklands Dash', checkpoints: docklands }, { id: 'lantern-loop', name: 'Lantern Loop', checkpoints: lantern }];
export class StreetRace {
  constructor(scene, rng) { this.scene = scene; this.rng = rng; this.active = false; this.meshes = []; this.rival = null; this.playerProgress = 0; this.rivalProgress = 0; }
  start(raceId, hooks = {}) { const race = RACES.find(r => r.id === raceId); if (!race) return false; this.abort(); this.race = race; this.hooks = hooks; this.elapsed = 0; this.playerProgress = this.rivalProgress = 0; this.active = true; this.checkpoints = race.checkpoints; this.rings = []; for (let i = 0; i < this.checkpoints.length; i++) { const p = this.checkpoints[i]; const group = new THREE.Group(); const ring = new THREE.Mesh(new THREE.TorusGeometry(6, 0.28, 8, 24), new THREE.MeshBasicMaterial({ color: 0xffcf58 })); ring.rotation.x = Math.PI / 2; group.add(ring); const pillar = new THREE.Mesh(new THREE.CylinderGeometry(0.18, 0.18, 8, 8), new THREE.MeshBasicMaterial({ color: 0xffcf58, transparent: true, opacity: 0.35 })); pillar.position.y = 4; group.add(pillar); group.position.set(p.x, 0, p.z); this.scene.add(group); this.meshes.push(group); this.rings.push(group); } this.rival = createCar(this.scene, 'komodo', 0x7b3fb5); this.rival.mesh.position.set(this.checkpoints[0].x + 4, 0, this.checkpoints[0].z); this.rival.heading = 0; return true; }
  update(dt, playerCar) { if (!this.active || !playerCar) return; this.elapsed += dt; const target = this.checkpoints[this.playerProgress]; if (target && playerCar.mesh.position.distanceTo(new THREE.Vector3(target.x, 0, target.z)) < 9) { this.playerProgress++; this.hooks.onCheckpoint?.(this.playerProgress, this.checkpoints.length); if (this.playerProgress >= this.checkpoints.length) { this.hooks.onFinish?.(true, this.elapsed); this.abort(); return; } } const rivalTarget = this.checkpoints[Math.min(this.rivalProgress, this.checkpoints.length - 1)]; const rp = this.rival.mesh.position; if (rp.distanceTo(new THREE.Vector3(rivalTarget.x, 0, rivalTarget.z)) < 9) this.rivalProgress++; const desired = Math.atan2(rivalTarget.x - rp.x, rivalTarget.z - rp.z); const delta = Math.atan2(Math.sin(desired - this.rival.heading), Math.cos(desired - this.rival.heading)); const gap = this.playerProgress - this.rivalProgress; driveStep(this.rival, dt, { throttle: THREE.MathUtils.clamp(0.95 + gap * 0.03, 0.92, 1.05), steer: THREE.MathUtils.clamp(delta * 2, -1, 1) }); for (let i = 0; i < this.rings.length; i++) this.rings[i].visible = i >= this.playerProgress && i <= this.playerProgress + 1; }
  get positions() { return this.playerProgress >= this.rivalProgress ? '1st' : '2nd'; }
  abort() { for (const mesh of this.meshes) this.scene.remove(mesh); this.meshes = []; if (this.rival) this.scene.remove(this.rival.mesh); this.rival = null; this.active = false; }
}
